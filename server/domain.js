export const reportSchema = z.object({
  title: z.string().trim().min(8).max(120),
  description: z.string().trim().min(15).max(2000),
  category: z.enum(categories),
  district: z.enum(Object.keys(districts)),
  address: z.string().trim().min(5).max(250),
  lat: z.number().min(-12.6).max(-11.5),
  lng: z.number().min(-77.3).max(-76.5),
  urgency: z.enum(["Baja", "Media", "Alta"]),
  photo: z
    .string()
    .regex(/^\/uploads\/[a-f0-9-]+\.webp$/)
    .nullable()
    .optional(),
  photo_alt: z.string().max(200).default(""),
  request_key: z.string().uuid().optional(),
});
