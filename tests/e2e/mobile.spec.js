import { test, expect } from "@playwright/test";
test("diseño móvil: menú, filtros, instalación y atajos", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await expect(page.locator(".app-hero")).toBeVisible();
  await page.screenshot({ path: "docs/capturas/09-redisenio-primer-pantalla.png" });
  await page.getByRole("button", { name: "Abrir navegación" }).click();
  const menu = page.getByRole("dialog", { name: "Menú de navegación" });
  await expect(menu).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(menu).not.toBeVisible();
  await page.goto("/dispositivo");
  await page.getByRole("button", { name: "Instalar en mi dispositivo" }).click();
  await expect(page.getByRole("dialog", { name: "Añadir a tu pantalla de inicio" })).toBeVisible();
  await page.getByRole("button", { name: "Entendido" }).click();
  await page.screenshot({ path: "docs/capturas/10-dispositivo-movil.png", fullPage: true });
  await page.goto("/mapa?category=Sem%C3%A1foros");
  await page.locator(".filter-summary button").first().click();
  const filters = page.getByRole("dialog", { name: "Encuentra lo que te importa" });
  await expect(filters).toBeVisible();
  await expect(filters.getByRole("combobox", { name: "Categoría", exact: true })).toHaveValue("Semáforos");
  await page.keyboard.press("Escape");
  await expect(filters).not.toBeVisible();
  await page.screenshot({ path: "docs/capturas/11-mapa-movil.png", fullPage: true });
  const manifest = await (await page.request.get("/manifest.webmanifest")).json();
  expect(manifest.display).toBe("standalone");
  expect(manifest.shortcuts).toHaveLength(3);
  await page.goto("/");
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});
